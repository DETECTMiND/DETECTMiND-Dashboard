# python3 scripts/gen-dark-theme.py > src/app/theme-dark.css
# Generates dark-theme overrides for the Tailwind palette classes the dashboard uses.
# Hue tints (50-300) and dark text (700-900) are swapped; 400-600 (buttons, icons) are left alone.
H = {
 'blue':   ['#dbeafe','#bfdbfe','#93c5fd','#60a5fa','#3b82f6'],
 'sky':    ['#e0f2fe','#bae6fd','#7dd3fc','#38bdf8','#0ea5e9'],
 'indigo': ['#e0e7ff','#c7d2fe','#a5b4fc','#818cf8','#6366f1'],
 'violet': ['#ede9fe','#ddd6fe','#c4b5fd','#a78bfa','#8b5cf6'],
 'purple': ['#f3e8ff','#e9d5ff','#d8b4fe','#c084fc','#a855f7'],
 'emerald':['#d1fae5','#a7f3d0','#6ee7b7','#34d399','#10b981'],
 'green':  ['#dcfce7','#bbf7d0','#86efac','#4ade80','#22c55e'],
 'teal':   ['#ccfbf1','#99f6e4','#5eead4','#2dd4bf','#14b8a6'],
 'cyan':   ['#cffafe','#a5f3fc','#67e8f9','#22d3ee','#06b6d4'],
 'amber':  ['#fef3c7','#fde68a','#fcd34d','#fbbf24','#f59e0b'],
 'yellow': ['#fef9c3','#fef08a','#fde047','#facc15','#eab308'],
 'orange': ['#ffedd5','#fed7aa','#fdba74','#fb923c','#f97316'],
 'red':    ['#fee2e2','#fecaca','#fca5a5','#f87171','#ef4444'],
 'rose':   ['#ffe4e6','#fecdd3','#fda4af','#fb7185','#f43f5e'],
 'pink':   ['#fce7f3','#fbcfe8','#f9a8d4','#f472b6','#ec4899'],
 'lime':   ['#ecfccb','#d9f99d','#bef264','#a3e635','#84cc16'],
 'fuchsia':['#fae8ff','#f5d0fe','#f0abfc','#e879f9','#d946ef'],
}
BASE = 'var(--surface)'
def mix(c, p): return f'color-mix(in oklab, {c} {p}%, {BASE})'
rules = []
def esc(cls): return cls.replace(':', '\\:').replace('/', '\\/').replace('.', '\\.')
def add(cls, prop, val, variants=('',)):
    for v in variants:
        sel = '.' + esc(v + cls) + (':hover' if v == 'hover:' else ':focus' if v == 'focus:' else '')
        rules.append((sel, prop, val))
for h, (c100, c200, c300, c400, c500) in H.items():
    add(f'bg-{h}-50', 'background-color', mix(c500, 12), ('', 'hover:'))
    add(f'bg-{h}-100', 'background-color', mix(c500, 20), ('', 'hover:'))
    add(f'bg-{h}-200', 'background-color', mix(c500, 32), ('', 'hover:'))
    add(f'bg-{h}-300', 'background-color', mix(c500, 45))
    for s, p in (('100', 22), ('200', 34), ('300', 46)):
        add(f'border-{h}-{s}', 'border-color', mix(c500, p), ('', 'hover:', 'focus:'))
        add(f'ring-{h}-{s}', '--tw-ring-color', mix(c500, p + 6))
    add(f'text-{h}-700', 'color', c300, ('', 'hover:'))
    add(f'text-{h}-800', 'color', c200, ('', 'hover:'))
    add(f'text-{h}-900', 'color', c100, ('', 'hover:'))
    add(f'text-{h}-600', 'color', c400, ('hover:',))
# Neutrals: gray and slate share one dark scale
N_BG = {'50': 'var(--page)', '100': 'var(--surface-sunken)', '200': 'var(--surface-raised)', '300': '#3a4a63'}
N_TEXT = {'300': '#4b5b74', '400': '#7d8ba3', '500': '#95a3b8', '600': '#aab6c8', '700': '#c9d3e0', '800': '#e2e8f0', '900': '#f1f5f9', '950': '#f8fafc'}
N_BORDER = {'50': '#1b2537', '100': '#1f2a3d', '200': 'var(--border)', '300': 'var(--border-strong)', '400': '#56677f'}
for n in ('gray', 'slate', 'zinc', 'neutral'):
    for s, v in N_BG.items(): add(f'bg-{n}-{s}', 'background-color', v, ('', 'hover:'))
    for s, v in N_TEXT.items(): add(f'text-{n}-{s}', 'color', v, ('', 'hover:'))
    for s, v in N_BORDER.items():
        add(f'border-{n}-{s}', 'border-color', v, ('', 'hover:', 'focus:'))
        add(f'ring-{n}-{s}', '--tw-ring-color', v)
        add(f'divide-{n}-{s}', '--dm-divide', v)
    add(f'placeholder-{n}-400', '--dm-ph', '1')
for c, v in (('bg-white', 'var(--surface)'), ('bg-white/95', 'color-mix(in oklab, var(--surface) 95%, transparent)'),
             ('bg-white/90', 'color-mix(in oklab, var(--surface) 90%, transparent)'), ('bg-white/80', 'color-mix(in oklab, var(--surface) 80%, transparent)'),
             ('bg-white/70', 'color-mix(in oklab, var(--surface) 70%, transparent)'), ('bg-white/60', 'color-mix(in oklab, var(--surface) 60%, transparent)')):
    add(c, 'background-color', v, ('', 'hover:'))
add('text-black', 'color', '#f8fafc')
out = ['/* Generated by scripts/gen-dark-theme.py: dark-theme overrides for palette classes (see globals.css). */']
for sel, prop, val in rules:
    if prop == '--dm-divide':
        out.append(f':root[data-theme="dark"] {sel} > :not(:last-child) {{ border-color: {val}; }}')
    elif prop == '--dm-ph':
        out.append(f':root[data-theme="dark"] {sel}::placeholder {{ color: #6b7a92; }}')
    else:
        out.append(f':root[data-theme="dark"] {sel} {{ {prop}: {val}; }}')
print('\n'.join(out))
